import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as T from '../../sunbreak-storm-v3/vendor/presentation/build/three.module.js';
import {installProceduralGround} from '../procedural-ground.js';
import {lowerSkySun,AFTERRAIN_LIGHT} from '../afterrain-light.js';
let checks=0;const check=(v,n)=>{assert.ok(v,n);checks++};
const layer={map:new T.Texture(),normalMap:new T.Texture(),roughnessMap:new T.Texture()},rain={value:0},time={value:3};
function shader(newLook){
 const m=new T.MeshStandardMaterial();Object.assign(m,layer);
 const uniforms={uPuddleReflection:{value:new T.Texture()},uPuddleProjection:{value:new T.Matrix4()},uPuddleReflectionEnabled:{value:1}};
 installProceduralGround(T,m,{dirt:layer,forest:layer,rain,time,afterRain:newLook?{uniforms}:null});
 const s={vertexShader:T.ShaderLib.standard.vertexShader,fragmentShader:T.ShaderLib.standard.fragmentShader,uniforms:{}};m.onBeforeCompile(s);return{s,m,uniforms};
}
const old=shader(false),now=shader(true);
check(!old.s.fragmentShader.includes('uPuddleReflection'),'previous has no added reflection code');
check(!old.s.vertexShader.includes('forestCover'),'previous no added geometry attribute');
check(old.m.customProgramCacheKey()!==now.m.customProgramCacheKey(),'cache separated');
check(now.s.uniforms.uPuddleProjection===now.uniforms.uPuddleProjection,'reflection live binding');
check(now.s.fragmentShader.includes('abs(vGroundWorld.y)'),'reflection restricted to true plane height');
check(now.s.fragmentShader.includes('basinFlatness*flatPlane'),'slope and height exclusion');
check(now.s.fragmentShader.includes('*(1.-vSurfaceZones.y)*(1.-vForestCover)'),'foundation and grass exclusions including litter gaps');
check(now.s.fragmentShader.includes('litterBlend=max(litterBlend,greenCover)'),'green cover drives litter normals too');
check(now.s.fragmentShader.includes('dot(litterSample.rgb'),'actual litter albedo detail preserved in green tint');
check(now.s.fragmentShader.includes('pondTransition=4.*puddle*(1.-puddle)'),'partial coverage dampens intermediate-roughness bright rim, not pool interiors');
for(const p of [0,.1,.25,.5,.75,.9,1])check(1-.98*4*p*(1-p)>=.02-1e-10,'nonnegative specular transition');
check(now.s.fragmentShader.includes('damp=max(damp,wetRim*.90)'),'wet rims independent from rain');
check(now.s.fragmentShader.includes('reflectedLight.indirectSpecular=mix('),'physical indirect reflection replacement not additive double IBL');
check(now.s.fragmentShader.includes('min(reflectedLight.indirectSpecular,vec3(.09)),wetRim'),'bound duplicate unshadowed solar soil lobe without clipping planar water');
check(now.s.fragmentShader.includes('pondFresnel=.025+.975*pow('),'dielectric Fresnel');
check(now.s.fragmentShader.includes('roughnessFactor=mix(roughnessFactor,.82,greenCover)'),'green ground remains matte');
check(!now.s.vertexShader.includes('transformed.y+='),'no terrain displacement/collision change');
check(now.s.fragmentShader.includes('uHeightFog')===false,'fog applied separately after terrain');
const source=await readFile(new URL('../puddle-reflection.js',import.meta.url),'utf8');
check(source.includes('o===terrain||o===water.mesh||o.isReflector'),'no feedback or nested reflection');
check(source.includes('samples:0')&&source.includes('multisample:0'),'bounded no-MSAA target');
check(source.includes('finally{haze.setReflection(false'),'reflection fog restored');
check(source.includes('renderer.shadowMap.needsUpdate=needs'),'shadow state restored');
const width=128,height=64,data=new Float32Array(width*height*4).fill(.2),sunPixel=16*width+47;data[sunPixel*4]=data[sunPixel*4+1]=data[sunPixel*4+2]=900;
const before=Buffer.from(data.buffer).toString('base64'),result=lowerSkySun({width,height,data},sunPixel);
check(before===Buffer.from(data.buffer).toString('base64'),'HDR input immutable');
check(result.data.every(Number.isFinite),'sky output finite');
check(result.sunPixel%width===47,'azimuth unchanged by elevation remap');
const latitude=(.5-(Math.floor(result.sunPixel/width)+.5)/height)*180;
check(Math.abs(latitude-26)<3,'measured solar elevation follows target');
for(let x=0;x<width;x++)check(result.data[(height/2*width+x)*4]>0,'horizon retained, no black gaps');
check(AFTERRAIN_LIGHT.sun>4&&AFTERRAIN_LIGHT.ambient<1.6&&AFTERRAIN_LIGHT.exposure<1.18,'contrast from light ratio, not exposure lift');
console.log(JSON.stringify({pass:true,checks,scope:'new shader/sky/RT source contracts, not rendered art/performance'}));
